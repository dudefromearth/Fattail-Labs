"""Provider webhook endpoints for native billing v2.  Spec §6.3.

Separate from routes/billing.py on purpose: that file is the v1.0 hosted-Checkout
integration and still serves live members. This mounts the v2 endpoints beside it
without touching it.

Both endpoints follow the same order, which is the point of §6.3:

    verify signature  ->  PERSIST  ->  acknowledge 200  ->  process

Returning 200 once the event is durably stored, before processing, is
deliberate: providers retry aggressively and Stripe disables endpoints that keep
failing. Storage is the acknowledgement; processing is our problem, and a
sweeper can retry it from the table.
"""

from __future__ import annotations

import json
import logging

import stripe
from fastapi import APIRouter, HTTPException, Request

import db
from config import get_config

from billing import events, webhooks

router = APIRouter(tags=["billing-webhooks"])
log = logging.getLogger("labs.billing.webhooks")


def _store_and_process(provider: str, event_ref: str, event_type: str,
                       created_at, payload: dict, handler) -> dict:
    with db.transaction() as conn:
        with conn.cursor() as cur:
            cur.execute("SET SESSION time_zone = '+00:00'")
            try:
                event_id = webhooks.ingest(
                    cur, provider=provider, event_ref=event_ref,
                    event_type=event_type, provider_created_at=created_at,
                    payload=payload)
            except webhooks.DuplicateEvent:
                # The NORMAL path, not an error. Providers resend constantly.
                return {"received": True, "duplicate": True}
    # Stored and committed. Now do the work in its own transaction so a
    # processing failure cannot lose the event.
    try:
        with db.transaction() as conn:
            with conn.cursor() as cur:
                cur.execute("SET SESSION time_zone = '+00:00'")
                result = handler(cur, payload)
                webhooks.mark_processed(cur, event_id, result)
    except Exception:
        log.exception("webhook %s %s stored but processing failed", provider, event_ref)
        return {"received": True, "stored": True, "processed": False}
    log.info("webhook %s %s: %s", provider, event_type, result)
    return {"received": True, "result": result}


@router.post("/api/billing/webhook/stripe")
async def stripe_v2(request: Request) -> dict:
    """Native-billing Stripe events (payment_intent.*, disputes, refunds).

    NOTE this endpoint will also receive events generated by WooCommerce's own
    charges — Stripe fans account-level events to every endpoint, and Woo bills
    through the same account. Those have no Labs ledger row and are recorded and
    ignored by events.handle_stripe. That is deliberate, not an oversight.
    """
    cfg = get_config()
    secret = cfg.stripe_webhook_secret
    if not secret:
        raise HTTPException(status_code=503, detail="Stripe webhook not configured")
    body = await request.body()
    sig = request.headers.get("Stripe-Signature", "")
    try:
        # SDK used for signature verification ONLY; the payload is handled as
        # plain JSON afterwards to avoid StripeObject accessor quirks.
        stripe.Webhook.construct_event(body, sig, secret)
    except Exception as exc:
        raise HTTPException(status_code=400, detail="Invalid signature") from exc

    payload = json.loads(body)
    from datetime import datetime, timezone
    created = payload.get("created")
    created_at = (datetime.fromtimestamp(created, tz=timezone.utc).replace(tzinfo=None)
                  if created else None)
    return _store_and_process("stripe", payload.get("id", ""), payload.get("type", ""),
                              created_at, payload, events.handle_stripe)


@router.post("/api/billing/webhook/paypal")
async def paypal_v2(request: Request) -> dict:
    """Native-billing PayPal events.

    PayPal verification is an API call, so it needs working credentials as well
    as PAYPAL_WEBHOOK_ID. It fails CLOSED — an unverifiable event is rejected.
    """
    cfg = get_config()
    webhook_id = getattr(cfg, "paypal_webhook_id", None)
    if not webhook_id:
        raise HTTPException(status_code=503, detail="PayPal webhook not configured")
    body = await request.body()

    from billing import providers
    try:
        prov = providers.for_name("paypal")
    except providers.ProviderError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    if not prov.verify_webhook(webhook_id=webhook_id,
                               headers=dict(request.headers), body=body):
        raise HTTPException(status_code=400, detail="Invalid signature")

    payload = json.loads(body)
    from datetime import datetime
    raw = (payload.get("create_time") or "").replace("Z", "+00:00")
    try:
        created_at = datetime.fromisoformat(raw).replace(tzinfo=None) if raw else None
    except ValueError:
        created_at = None
    return _store_and_process("paypal", payload.get("id", ""),
                              payload.get("event_type", ""), created_at,
                              payload, events.handle_paypal)
